/// Every stylesheet in [`ALL`], joined in order, each under a comment naming
/// its file.
pub fn bundle() -> String {
    let mut out = String::from(
        "/* Shonin's atoms and components (sh-*), from packages/frontend/ui/styles. Generated by `task frontend:tokens`. */\n",
    );
    for (name, css) in ALL {
        out.push_str(&format!("\n/* --- {name}.css --- */\n"));
        out.push_str(css);
    }
    out
}

/// The stylesheet one atom or component lives in.
pub fn get(name: &str) -> Option<&'static str> {
    ALL.iter()
        .find(|(file, _)| *file == name)
        .map(|(_, css)| *css)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A colour typed into a stylesheet would drift from the design's
    /// tokens; every colour comes from a custom property.
    #[test]
    fn no_stylesheet_types_in_a_colour() {
        for (name, css) in ALL {
            for (index, line) in css.lines().enumerate() {
                let code = line.split("/*").next().unwrap_or("");
                assert!(
                    !code.contains('#')
                        || code.trim_start().starts_with('#') && !code.contains(':'),
                    "styles/{name}.css:{} types in a colour: {line}",
                    index + 1
                );
                for function in ["rgb(", "rgba(", "hsl("] {
                    assert!(
                        !code.contains(function),
                        "styles/{name}.css:{} types in a colour: {line}",
                        index + 1
                    );
                }
            }
        }
    }

    #[test]
    fn every_class_is_namespaced() {
        for (name, css) in ALL {
            for word in css
                .split(|c: char| !(c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.'))
            {
                if let Some(class) = word.strip_prefix('.')
                    && class.starts_with(|c: char| c.is_ascii_alphabetic())
                {
                    assert!(
                        class.starts_with("sh-") || class.starts_with("t-"),
                        "styles/{name}.css names a class outside sh-*: .{class}"
                    );
                }
            }
        }
    }

    #[test]
    fn hover_styles_apply_only_where_something_can_hover() {
        for (name, css) in ALL {
            let mut depth_in_hover = 0usize;
            let mut in_hover_block = false;
            for line in css.lines() {
                if line.contains("@media (hover: hover)") {
                    in_hover_block = true;
                    depth_in_hover = 0;
                }
                if in_hover_block {
                    depth_in_hover += line.matches('{').count();
                    depth_in_hover = depth_in_hover.saturating_sub(line.matches('}').count());
                    if depth_in_hover == 0 {
                        in_hover_block = false;
                    }
                    continue;
                }
                assert!(
                    !line.contains(":hover"),
                    "styles/{name}.css styles :hover outside @media (hover: hover): {line}"
                );
            }
        }
    }

    #[test]
    fn the_bundle_holds_every_sheet_in_order() {
        let bundle = bundle();
        let mut at = 0;
        for (name, _) in ALL {
            let found = bundle[at..].find(&format!("/* --- {name}.css --- */"));
            assert!(found.is_some(), "{name} is missing or out of order");
            at += found.unwrap();
        }
        assert!(get("button").unwrap().contains(".sh-btn"));
    }
}
