//! One stylesheet per atom and component, as `sh-*` classes written only in
//! the tokens' custom properties: no colour, radius or spacing is typed in by
//! hand. Both sites include the same files, so an atom looks the same on
//! shonin.fi and app.shonin.fi.
//!
//! [`ALL`] is in cascade order: base and layout first, then atoms, then the
//! page chrome. [`bundle`] joins them into the one stylesheet a page links.

