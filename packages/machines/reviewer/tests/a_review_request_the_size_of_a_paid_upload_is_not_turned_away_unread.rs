//! The build service takes an upload of up to 20 MiB on the wire: a project
//! at the 2 MiB source limit in up to 10,000 files, each costing the archive
//! a 512-byte header and up to 511 bytes of padding, carried as base64 in a
//! JSON envelope. Once such a project is paid for, the build service hands
//! the reviewer the whole archive, the same way, in a `ReviewRequest`.
//!
//! A review request as large as a paid upload may be reaches the reviewer's
//! handler: the reviewer takes a request up to the same bound the upload
//! route does. One turned away unread (413, from a body limit lower than an
//! upload's) would never be reviewed, however often it was asked again, for
//! a project that passed every check made before payment.
//!
//! Here a project within every pre-payment limit (the source budget, the
//! reviewer's reading budget, the dependency checks) is spread over 2,000
//! small files, as a project vendoring its own crates might be. Its archive
//! comes to a little over 2 MiB, 2.7 MiB as base64. The reviewer's chain is
//! out of reach, so the handler's own answer is 503 (ask again later): any
//! answer the handler gives is fine, as long as the request was read.

mod black_box;

fn project_in_many_files(files: usize, each: usize) -> Vec<u8> {
    let root = black_box::scratch().join("project");
    std::fs::create_dir_all(root.join("src")).unwrap();
    std::fs::write(root.join("Cargo.toml"), "[package]\nname = \"agent\"\n").unwrap();
    std::fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\n\
         name = \"agent\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::fs::write(
        root.join("shonin.toml"),
        "[vault]\nchain = \"base\"\n[description]\ntitle = \"An agent\"\ntext = \"x\"\n\
         [drivers.local]\n",
    )
    .unwrap();
    for n in 0..files {
        std::fs::write(root.join(format!("src/m{n:04}.rs")), "/".repeat(each)).unwrap();
    }
    let packed = shared::archive::pack(&root).unwrap();
    let _ = std::fs::remove_dir_all(root.parent().unwrap());
    packed
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_review_request_the_size_of_a_paid_upload_is_not_turned_away_unread() {
    let archive = project_in_many_files(2_000, 100);

    // The build service would take this upload and let it be paid for.
    assert!(
        shared::archive::reviewed(&archive).is_ok(),
        "the project is within what the reviewer reads in one review"
    );
    assert!(
        shared::dependencies::checked(
            &archive,
            "shonin.toml",
            &shared::dependencies::Allowlist::platform()
        )
        .is_ok(),
        "the project depends on nothing outside itself"
    );
    let on_the_wire = shared::base64::encode(&archive).len();
    assert!(
        on_the_wire < shared::archive::MOST_UPLOAD_BYTES,
        "the upload is within the body limit: {on_the_wire} bytes"
    );
    assert!(
        on_the_wire > 2 * 1024 * 1024,
        "the request is past 2 MiB, as a paid project may be: {on_the_wire} bytes"
    );

    let reviewer = black_box::start(black_box::Options {
        node: false,
        ..Default::default()
    })
    .await;
    let (status, body) = reviewer.review(7, &archive).await;
    assert_ne!(
        status, 413,
        "a review request the size of a paid upload ({on_the_wire} bytes) was turned away \
         unread, so it could never be reviewed: {body}"
    );
    assert_eq!(
        status, 503,
        "the reviewer, its chain out of reach, did not answer ask-again-later: {body}"
    );
}
